/** Inspect one built, bundled VSIX without installing or publishing it. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const artifact = process.argv[2];
if (!artifact) throw new Error('Usage: node scripts/inspect-vsix.cjs <artifact.vsix> [report.json]');
const root = path.resolve(__dirname, '..');
const read = name => execFileSync('unzip', ['-p', artifact, `extension/${name}`], { maxBuffer: 32 * 1024 * 1024 });
const entries = execFileSync('unzip', ['-Z1', artifact], { encoding: 'utf8' }).trim().split('\n');
const manifestBytes = read('package.json');
const manifest = JSON.parse(manifestBytes);
assert.equal(`${manifest.publisher}.${manifest.name}`, 'phfsantos.markdown-editor');
assert.equal(manifest.displayName, 'Markdown Studio');
assert.equal(manifest.contributes.customEditors.length, 1);
assert.equal(manifest.contributes.customEditors[0].viewType, 'markdown-editor');
assert.equal(manifest.icon, 'media/logo.png');
assert.ok(manifestBytes.equals(fs.readFileSync(path.join(root, 'package.json'))), 'Packaged manifest differs from source');
assert.ok(read(manifest.icon).equals(fs.readFileSync(path.join(root, manifest.icon))), 'Packaged icon differs from source');
assert.ok(read('media/screenshot-main.png').equals(fs.readFileSync(path.join(root, 'media/screenshot-main.png'))), 'Packaged screenshot differs from source');
const forbidden = entries.filter(name => /(^|\/)(src|scripts|test|tests|node_modules|\.git|\.env)(\/|$)|\.map$|test-usage\.json/.test(name));
assert.deepEqual(forbidden, [], 'Development files or local reports leaked into the VSIX');
const runtime = ['dist/extension.js', 'out/media/main.js', 'out/media/main.css', 'out/widgets/index.js', 'media/sidebar-icon.svg'];
for (const name of runtime) assert.ok(entries.includes(`extension/${name}`), `Missing runtime asset ${name}`);
for (const name of ['dist/extension.js', 'out/media/main.js', 'out/widgets/index.js']) assert.ok(read(name).equals(fs.readFileSync(path.join(root, name))), `Stale runtime bundle ${name}`);
const readme = read('readme.md').toString();
assert.match(readme, /# Markdown Studio/);
assert.doesNotMatch(readme, /What's New in 0\.4\.7|0 vulnerabilities|all tests passing/i);
const report = { artifact: path.resolve(artifact), version: manifest.version, id: `${manifest.publisher}.${manifest.name}`, displayName: manifest.displayName, bytes: fs.statSync(artifact).size, sha256: crypto.createHash('sha256').update(fs.readFileSync(artifact)).digest('hex'), entries: entries.length, forbidden, sourceManifestMatches: true, sourceIconMatches: true, runtimeBundlesMatch: true, runtime, readmeImages: [...readme.matchAll(/(?:src="|!\[[^\]]*\]\()([^"\s)]+)/g)].map(match => match[1]) };
if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
